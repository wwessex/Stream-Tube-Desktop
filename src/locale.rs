/// Display name for a code from `list`, or the code itself.
pub fn name<'a>(list: &[(&str, &'a str)], code: &'a str) -> &'a str {
    list.iter().find(|(c, _)| c.eq_ignore_ascii_case(code)).map(|(_, n)| *n).unwrap_or(code)
}
